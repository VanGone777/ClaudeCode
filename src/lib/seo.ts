import type { Metadata } from "next";
import { site } from "@/content/site";

export function absoluteUrl(path = "/"): string {
  const base = site.url.replace(/\/$/, "");
  return path.startsWith("http") ? path : `${base}${path.startsWith("/") ? path : `/${path}`}`;
}

type BuildMetadataInput = {
  title: string;
  description: string;
  path: string;
  /** Use the title verbatim (no "– Goldnest" suffix). */
  absoluteTitle?: boolean;
  type?: "website" | "article";
  publishedTime?: string;
  modifiedTime?: string;
  noIndex?: boolean;
  locale?: "de_AT" | "en_US";
  alternates?: Record<string, string>;
};

/**
 * Builds the page Metadata object: title, description, canonical, OpenGraph, Twitter.
 * The OpenGraph image is generated by app/opengraph-image.tsx and inherited.
 */
export function buildMetadata({
  title,
  description,
  path,
  absoluteTitle = false,
  type = "website",
  publishedTime,
  modifiedTime,
  noIndex = false,
  locale = "de_AT",
  alternates,
}: BuildMetadataInput): Metadata {
  const canonical = absoluteUrl(path);
  const fullTitle = absoluteTitle ? title : `${title} – Goldnest`;
  return {
    title: absoluteTitle ? { absolute: title } : title,
    description,
    alternates: {
      canonical,
      ...(alternates ? { languages: alternates } : {}),
    },
    openGraph: {
      type,
      locale,
      url: canonical,
      siteName: site.legalName,
      title: fullTitle,
      description,
      ...(type === "article" ? { publishedTime, modifiedTime, authors: [site.legalName] } : {}),
    },
    twitter: {
      card: "summary_large_image",
      title: fullTitle,
      description,
    },
    ...(noIndex ? { robots: { index: false, follow: false } } : {}),
  };
}
